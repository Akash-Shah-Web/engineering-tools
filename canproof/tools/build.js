#!/usr/bin/env node
/*
 * Build the single self-contained page canproof/index.html (GitHub Pages).
 * Inlines: CSS, vendored three.js (licence header kept), core.js, charts,
 * 3D scene, app, and the example datasets:
 *   - data/synthetic/demo_vehicle.{dbc,summary.json}   (SYNTHETIC, labelled)
 *   - data/samples/*.summary.json (+ matching .dbc)      (MEASURED samples, if present and licence allows)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const rd = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const safeJs = (s) => s.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

function examples() {
  const out = [];
  const samplesDir = path.join(root, 'data', 'samples');
  if (fs.existsSync(samplesDir)) {
    for (const f of fs.readdirSync(samplesDir).filter((x) => x.endsWith('.summary.json')).sort()) {
      const summary = JSON.parse(fs.readFileSync(path.join(samplesDir, f), 'utf8'));
      const dbcPath = path.join(samplesDir, f.replace('.summary.json', '.dbc'));
      out.push({
        id: f.replace('.summary.json', ''), title: summary.provenance.source, label: summary.provenance.label,
        dbc: fs.existsSync(dbcPath) ? fs.readFileSync(dbcPath, 'utf8') : null, bitrate: summary.bitrate, summary,
        description: `${summary.frames.toLocaleString()} frames, ${summary.duration.toFixed(1)} s.`,
      });
    }
  }
  const synDir = path.join(root, 'data', 'synthetic');
  const sum = JSON.parse(fs.readFileSync(path.join(synDir, 'demo_vehicle.summary.json'), 'utf8'));
  out.push({
    id: 'synthetic-demo', title: 'Synthetic demo vehicle (29 messages, 500 kbit/s)', label: 'synthetic', bitrate: 500000,
    dbc: fs.readFileSync(path.join(synDir, 'demo_vehicle.dbc'), 'utf8'), summary: sum,
    description: 'An original, unbranded network generated by tools/make_synthetic.js; its trace was produced by the CANProof simulator, so agreement with the model is expected and is NOT validation.',
  });
  return out;
}

function build() {
  const tpl = rd('src/ui.html');
  const three = rd('vendor/three-0.158.0.min.js');
  const threeHeader = '/*! three.js r158 — https://threejs.org — MIT License\n' + rd('vendor/three-LICENSE.txt').replace(/\*\//g, '* /') + '*/\n';
  const data = JSON.stringify({ built: new Date().toISOString().slice(0, 10), examples: examples() }).replace(/<\//g, '<\\/');
  const parts = {
    '/*{{CSS}}*/': rd('src/ui.css'),
    '/*{{THREE}}*/': safeJs(threeHeader + three),
    '/*{{CORE}}*/': safeJs(rd('src/core.js')),
    '/*{{DATA}}*/null': data,
    '/*{{CHARTS}}*/': safeJs(rd('src/charts.js')),
    '/*{{CAR}}*/': safeJs(rd('src/car3d.js')),
    '/*{{APP}}*/': safeJs(rd('src/app.js')),
  };
  let html = tpl;
  for (const [k, v] of Object.entries(parts)) {
    if (!html.includes(k)) throw new Error('placeholder missing: ' + k);
    html = html.split(k).join(v);
  }
  if (/https?:\/\/(cdn|unpkg|fonts\.)/.test(html.replace(/https:\/\/threejs\.org/g, ''))) console.warn('warning: external URL found in build');
  fs.writeFileSync(path.join(root, 'index.html'), html);
  console.log(`index.html ${(html.length / 1e6).toFixed(2)} MB, ${examples().length} example(s)`);
}
build();
