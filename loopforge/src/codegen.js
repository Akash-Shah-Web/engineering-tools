/*
 * LoopForge C code generator.
 * Emits header-only C99 controllers in floating point and Q16.16 fixed point.
 * Every emitted line carries tags naming the control setting it implements,
 * so the UI can highlight the code related to the slider being moved.
 *
 * Tags: kc ti td n b ts aw sat model fixed api
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory(require('./core.js'));
  else root.LoopForgeCodegen = factory(root.LoopForge);
})(typeof self !== 'undefined' ? self : this, function (LF) {
  'use strict';

  const g17 = x => {
    if (!isFinite(x)) throw new Error('non-finite coefficient');
    let s = Number(x).toPrecision(17);
    s = s.replace(/(\.\d*?)0+(e|$)/, '$1$2').replace(/\.(e|$)/, '.0$1');
    if (!/[.e]/.test(s)) s += '.0';
    return s;
  };
  const fmt = (x, d) => (Math.abs(x) >= 1e5 || (Math.abs(x) < 1e-3 && x !== 0) ? x.toExponential(d) : x.toFixed(d));

  function header(cfg, title) {
    const m = cfg.model, c = cfg.ctrl, mg = cfg.margins || {};
    const L = [];
    const add = (text, tags) => L.push({ text, tags: tags || [] });
    add('/*');
    add(` * ${title}`);
    add(' * Generated by LoopForge — https://github.com/Akash-Shah-Web/engineering-tools (loopforge/)');
    add(' *');
    if (m.type === 'SOPDT')
      add(` * Plant model (${cfg.source || 'user data'}): G(s) = ${fmt(m.K, 4)} e^(-${fmt(m.theta, 2)}s) / ((${fmt(m.tau1, 2)}s+1)(${fmt(m.tau2, 2)}s+1))`, ['model']);
    else
      add(` * Plant model (${cfg.source || 'user data'}): G(s) = ${fmt(m.K, 4)} e^(-${fmt(m.theta, 2)}s) / (${fmt(m.tau1, 2)}s+1)`, ['model']);
    if (cfg.fitPct !== undefined) add(` * Fit on identification data: NRMSE fit ${cfg.fitPct.toFixed(1)} %, RMSE ${cfg.rmse.toFixed(3)} (output units)`, ['model']);
    add(` * Tuning: ${c.ref || c.method + ' ' + c.type}${c.tauC !== undefined ? `, tau_c/lambda = ${fmt(c.tauC, 2)} s` : ''}`, ['kc', 'ti', 'td']);
    add(` * Ideal-form gains: Kc = ${fmt(c.Kc, 5)}, Ti = ${fmt(c.Ti, 3)} s${c.Td > 0 ? `, Td = ${fmt(c.Td, 3)} s, N = ${c.N || 10}` : ' (PI)'}, b = ${c.b === undefined ? 1 : c.b}`, ['kc', 'ti', 'td', 'n', 'b']);
    add(` * Sample time Ts = ${g17(cfg.Ts)} s.  Output limits [${cfg.umin}, ${cfg.umax}].`, ['ts', 'sat']);
    add(` * Anti-windup: ${{ none: 'none', clamp: 'conditional integration (clamping)', backcalc: `back-calculation, Tt = ${fmt(cfg.coeffs.Tt, 3)} s` }[c.antiWindup || 'backcalc']}`, ['aw']);
    if (mg.gmDb !== undefined)
      add(` * Sampled-loop margins (model): GM ${isFinite(mg.gmDb) ? mg.gmDb.toFixed(2) + ' dB' : 'inf'}, PM ${isFinite(mg.pm) ? mg.pm.toFixed(1) + ' deg' : 'inf'}, Ms ${mg.Ms.toFixed(2)}`, ['kc', 'ti', 'td', 'ts']);
    add(' *');
    add(' * Discretisation: forward-Euler integral, backward-difference derivative with');
    add(' * first-order filter Tf = Td/N, derivative acting on the measurement only.');
    add(' * Call the step function exactly once every Ts seconds (timer interrupt).');
    add(' * Margins describe the fitted model, not the physical plant: validate on hardware.');
    add(' */');
    return L;
  }

  function generateFloat(cfg) {
    const c = cfg.coeffs, aw = cfg.ctrl.antiWindup || 'backcalc';
    const L = header(cfg, 'Discrete PID controller — floating point');
    const add = (text, tags) => L.push({ text, tags: tags || [] });
    add('#ifndef LOOPFORGE_PID_H');
    add('#define LOOPFORGE_PID_H');
    add('');
    add('#ifdef LF_USE_DOUBLE');
    add('typedef double lf_real;');
    add('#else');
    add('typedef float lf_real;        /* single precision suits Cortex-M4F/M7 FPUs */');
    add('#endif');
    add('#define LF_R(x) ((lf_real)(x))');
    add('');
    add(`#define LF_TS   ${g17(cfg.Ts)}   /* sample time [s] */`, ['ts']);
    add(`#define LF_KP   LF_R(${g17(c.kp)})   /* Kc */`, ['kc']);
    add(`#define LF_KB   LF_R(${g17(c.kb)})   /* b*Kc (setpoint weight) */`, ['kc', 'b']);
    add(`#define LF_KI   LF_R(${g17(c.ki)})   /* Kc*Ts/Ti */`, ['kc', 'ti', 'ts']);
    if (c.hasD) {
      add(`#define LF_AD   LF_R(${g17(c.ad)})   /* Tf/(Tf+Ts), Tf = Td/N */`, ['td', 'n', 'ts']);
      add(`#define LF_BD   LF_R(${g17(c.bd)})   /* Kc*Td/(Tf+Ts) */`, ['kc', 'td', 'n', 'ts']);
    }
    if (aw === 'backcalc') add(`#define LF_KT   LF_R(${g17(c.kt)})   /* Ts/Tt, back-calculation gain */`, ['aw', 'ts']);
    add(`#define LF_UMIN LF_R(${g17(cfg.umin)})`, ['sat']);
    add(`#define LF_UMAX LF_R(${g17(cfg.umax)})`, ['sat']);
    add('');
    add('typedef struct {', ['api']);
    add('    lf_real i;       /* integral state */', ['ti']);
    if (c.hasD) add('    lf_real d;       /* filtered derivative state */', ['td']);
    add('    lf_real y_prev;  /* previous measurement */', c.hasD ? ['td'] : []);
    add('} lf_pid_t;', ['api']);
    add('');
    add('/* Bumpless start: state chosen so that u = u0 when r = y = y0. */', ['api']);
    add('static inline void lf_pid_init(lf_pid_t *s, lf_real y0, lf_real u0)', ['api']);
    add('{');
    add('    s->i = u0 - LF_KB * y0 + LF_KP * y0;', ['ti', 'b']);
    if (c.hasD) add('    s->d = LF_R(0.0);', ['td']);
    add('    s->y_prev = y0;');
    add('}');
    add('');
    add('/* One controller update: r = setpoint, y = measurement; returns actuator command. */', ['api']);
    add('static inline lf_real lf_pid_step(lf_pid_t *s, lf_real r, lf_real y)', ['api']);
    add('{');
    add('    const lf_real e = r - y;');
    add('    const lf_real p = LF_KB * r - LF_KP * y;', ['kc', 'b']);
    if (c.hasD) add('    s->d = LF_AD * s->d - LF_BD * (y - s->y_prev);', ['td', 'n']);
    add(`    const lf_real v = p + s->i${c.hasD ? ' + s->d' : ''};`);
    add('    const lf_real u = v > LF_UMAX ? LF_UMAX : (v < LF_UMIN ? LF_UMIN : v);', ['sat']);
    add('    const lf_real di = LF_KI * e;', ['ti']);
    if (aw === 'backcalc') add('    s->i += di + LF_KT * (u - v);            /* back-calculation */', ['aw', 'ti']);
    else if (aw === 'clamp') {
      add('    if (!((v > LF_UMAX && di > LF_R(0.0)) || (v < LF_UMIN && di < LF_R(0.0))))', ['aw']);
      add('        s->i += di;                             /* conditional integration */', ['aw', 'ti']);
    } else add('    s->i += di;                                 /* no anti-windup */', ['aw', 'ti']);
    add('    s->y_prev = y;');
    add('    return u;');
    add('}');
    add('');
    add('#endif /* LOOPFORGE_PID_H */');
    return L;
  }

  function generateFixed(cfg) {
    const fc = cfg.fixed, aw = cfg.ctrl.antiWindup || 'backcalc';
    const L = header(cfg, 'Discrete PID controller — fixed point (Q16.16 signals)');
    const add = (text, tags) => L.push({ text, tags: tags || [] });
    const coef = (name, q, comment, tags) => {
      add(`#define LF_${name}_Q  (${q.q}L)  /* ${comment} ~= ${g17(q.q / 2 ** q.f)} */`, tags.concat('fixed'));
      add(`#define LF_${name}_F  ${q.f}`, tags.concat('fixed'));
    };
    add('#ifndef LOOPFORGE_PID_Q16_H');
    add('#define LOOPFORGE_PID_Q16_H');
    add('');
    add('#include <stdint.h>');
    add('');
    add('/* Number formats');
    add(' *   signals (r, y, u, derivative state): Q16.16 in int32_t, range +/-32768, LSB 1.53e-5', ['fixed']);
    add(' *   integral state: Q32.32 in int64_t (keeps small Ki*e increments from vanishing)', ['fixed', 'ti']);
    add(' *   coefficient c is stored as round(c * 2^F) in int32_t with its own F (<= 30)', ['fixed']);
    add(' * Requires arithmetic right shift of negative int64_t (true for GCC, Clang, IAR, Keil). */', ['fixed']);
    add('#define LF_TO_Q16(x) ((int32_t)((x) * 65536.0 + ((x) >= 0 ? 0.5 : -0.5)))  /* engineering units -> Q16.16 */', ['fixed']);
    add(`#define LF_TS   ${g17(cfg.Ts)}   /* sample time [s] */`, ['ts']);
    coef('KP', fc.kp, 'Kc', ['kc']);
    coef('KB', fc.kb, 'b*Kc', ['kc', 'b']);
    coef('KI', fc.ki, 'Kc*Ts/Ti', ['kc', 'ti', 'ts']);
    if (fc.hasD) { coef('AD', fc.ad, 'Tf/(Tf+Ts)', ['td', 'n', 'ts']); coef('BD', fc.bd, 'Kc*Td/(Tf+Ts)', ['kc', 'td', 'n', 'ts']); }
    if (aw === 'backcalc') coef('KT', fc.kt, 'Ts/Tt', ['aw', 'ts']);
    add(`#define LF_UMIN_Q (${fc.umin}L)  /* ${cfg.umin} */`, ['sat', 'fixed']);
    add(`#define LF_UMAX_Q (${fc.umax}L)  /* ${cfg.umax} */`, ['sat', 'fixed']);
    add('');
    add('static inline int64_t lf_rshift(int64_t x, int s)   /* round-half-up shift */', ['fixed']);
    add('{');
    add('    return s > 0 ? (x + ((int64_t)1 << (s - 1))) >> s : x * ((int64_t)1 << -s);', ['fixed']);
    add('}');
    add('static inline int64_t lf_sat32(int64_t x)', ['fixed']);
    add('{');
    add('    return x > INT32_MAX ? INT32_MAX : (x < INT32_MIN ? INT32_MIN : x);', ['fixed']);
    add('}');
    add('#define LF_MULQ(name, x) lf_rshift((int64_t)LF_##name##_Q * (int64_t)(x), LF_##name##_F)', ['fixed']);
    add('');
    add('typedef struct {', ['api']);
    add('    int64_t i;       /* integral state, Q32.32 */', ['ti', 'fixed']);
    if (fc.hasD) add('    int32_t d;       /* filtered derivative, Q16.16 */', ['td', 'fixed']);
    add('    int32_t y_prev;  /* previous measurement, Q16.16 */');
    add('} lf_pid_q16_t;', ['api']);
    add('');
    add('static inline void lf_pid_q16_init(lf_pid_q16_t *s, int32_t y0, int32_t u0)', ['api']);
    add('{');
    add('    s->i = ((int64_t)u0 - LF_MULQ(KB, y0) + LF_MULQ(KP, y0)) * 65536;', ['ti', 'b', 'fixed']);
    if (fc.hasD) add('    s->d = 0;', ['td']);
    add('    s->y_prev = y0;');
    add('}');
    add('');
    add('/* r, y and the return value are Q16.16 (engineering units * 65536). */', ['api']);
    add('static inline int32_t lf_pid_q16_step(lf_pid_q16_t *s, int32_t r, int32_t y)', ['api']);
    add('{');
    add('    const int64_t e = lf_sat32((int64_t)r - y);');
    add('    const int64_t p = LF_MULQ(KB, r) - LF_MULQ(KP, y);', ['kc', 'b']);
    if (fc.hasD) add('    s->d = (int32_t)lf_sat32(LF_MULQ(AD, s->d) - LF_MULQ(BD, lf_sat32((int64_t)y - s->y_prev)));', ['td', 'n']);
    add(`    const int64_t v = lf_sat32(p + lf_rshift(s->i, 16)${fc.hasD ? ' + s->d' : ''});`);
    add('    const int64_t u = v > LF_UMAX_Q ? LF_UMAX_Q : (v < LF_UMIN_Q ? LF_UMIN_Q : v);', ['sat']);
    add('    const int64_t di = lf_rshift((int64_t)LF_KI_Q * e, LF_KI_F - 16);   /* Q32.32 */', ['ti']);
    if (aw === 'backcalc') add('    s->i += di + lf_rshift((int64_t)LF_KT_Q * lf_sat32(u - v), LF_KT_F - 16);', ['aw', 'ti']);
    else if (aw === 'clamp') {
      add('    if (!((v > LF_UMAX_Q && di > 0) || (v < LF_UMIN_Q && di < 0)))', ['aw']);
      add('        s->i += di;', ['aw', 'ti']);
    } else add('    s->i += di;', ['aw', 'ti']);
    add('    s->y_prev = y;');
    add('    return (int32_t)u;');
    add('}');
    add('');
    add('#endif /* LOOPFORGE_PID_Q16_H */');
    return L;
  }

  function generateExample(cfg) {
    const L = [];
    const add = (text, tags) => L.push({ text, tags: tags || [] });
    add('/* Example: TCLab-style heater loop on an Arduino-class MCU (illustrative).');
    add(' * read_temperature_c() and set_heater_percent() are board-specific. */', ['api']);
    add('#include "loopforge_pid.h"');
    add('');
    add('static lf_pid_t pid;');
    add(`static lf_real setpoint_c = LF_R(${cfg.r1 !== undefined ? cfg.r1 : 50});`);
    add('');
    add('void controller_setup(void)', ['api']);
    add('{');
    add('    lf_real t0 = read_temperature_c();');
    add('    lf_pid_init(&pid, t0, LF_R(0.0));     /* heater off, bumpless */');
    add('    start_periodic_timer_seconds(LF_TS);   /* fires controller_tick() */', ['ts']);
    add('}');
    add('');
    add('void controller_tick(void)                 /* every LF_TS seconds */', ['ts']);
    add('{');
    add('    lf_real y = read_temperature_c();');
    add('    lf_real u = lf_pid_step(&pid, setpoint_c, y);', ['api']);
    add('    set_heater_percent(u);                 /* already limited to [LF_UMIN, LF_UMAX] */', ['sat']);
    add('}');
    return L;
  }

  /**
   * cfg: {model, ctrl:{Kc,Ti,Td,N,b,antiWindup,Tt,method,type,ref,tauC}, Ts, umin, umax,
   *       margins, source, fitPct, rmse, r1}
   */
  function generate(cfg) {
    cfg = Object.assign({}, cfg);
    cfg.coeffs = LF.controllerCoeffs(cfg.ctrl, cfg.Ts);
    cfg.fixed = LF.fixedCoeffs(cfg.ctrl, cfg.Ts, { umin: cfg.umin, umax: cfg.umax });
    const files = [
      { name: 'loopforge_pid.h', lang: 'c', lines: generateFloat(cfg) },
      { name: 'loopforge_pid_q16.h', lang: 'c', lines: generateFixed(cfg) },
      { name: 'example_main.c', lang: 'c', lines: generateExample(cfg) },
    ];
    files.forEach(f => { f.text = f.lines.map(l => l.text).join('\n') + '\n'; });
    return { files, coeffs: cfg.coeffs, fixed: cfg.fixed };
  }

  return { generate, g17 };
});
