// Writes data/synthetic/synthetic_sopdt_step.csv — SYNTHETIC data, for testing the import path only.
'use strict';
const fs = require('fs'), path = require('path');
const LF = require('../src/core.js');
const truth = { K: 1.25, tau1: 45, tau2: 6, theta: 3.5 };
const t = [], u = [];
for (let i = 0; i < 600; i++) { t.push(+(i * 0.5).toFixed(2)); u.push(i < 20 ? 10 : i < 320 ? 40 : 25); }
const x = LF.simulateModel(truth, t, u, 10), R = LF.rng(42);
const lines = ['# SYNTHETIC — generated by tools/make_synthetic.js, not measured.',
  `# truth: SOPDT K=${truth.K} tau1=${truth.tau1} tau2=${truth.tau2} theta=${truth.theta}, u before t0 = 10, noise sigma 0.05`,
  'time_s,valve_pct,flow'];
for (let i = 0; i < t.length; i++) lines.push(`${t[i]},${u[i]},${(5 + x[i] + 0.05 * R.n()).toFixed(4)}`);
fs.mkdirSync(path.join(__dirname, '..', 'data', 'synthetic'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'data', 'synthetic', 'synthetic_sopdt_step.csv'), lines.join('\n') + '\n');
console.log('wrote', lines.length - 3, 'rows');
